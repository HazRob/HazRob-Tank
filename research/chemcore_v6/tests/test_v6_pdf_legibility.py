#!/usr/bin/env python3
"""Inspect *actual Android PdfRenderer output PDF* for V6 evidence readability.

CI test only: this is NOT a scientific concentration validation. The PDF
must be generated by the temporary Android emulator fixture first.
"""
import argparse
import json
import re


def validate(path,expected_pages=4):
    import fitz  # Only required when inspecting a downloaded emulator PDF artifact.
    doc=fitz.open(path)
    assert doc.page_count==expected_pages,(doc.page_count,expected_pages)
    per_page=[]
    all_text=[]
    total_mq=0
    for k,page in enumerate(doc):
        assert abs(page.rect.width-842)<1 and abs(page.rect.height-595)<1
        spans=[]
        for block in page.get_text("dict")["blocks"]:
            for line in block.get("lines",[]):
                for span in line["spans"]:
                    if span["text"].strip():
                        spans.append(span)
        assert spans,f"page {k+1} blank"
        for span in spans:
            a,b,c,d=span["bbox"]
            assert 25<=a<c<=829,(k,span["text"],span["bbox"])
            assert 12<=b<d<=575,(k,span["text"],span["bbox"])
        text=" ".join(s["text"] for s in spans)
        all_text.append(text)
        assert "UNKNOWN" in text and "G3=0" in text,(
            "research-only UNKNOWN and G3 marker missing",k)
        mq=[s for s in spans if re.fullmatch(r"MQ(?:2|3|4|5|7|8|9|135)",
                                              s["text"].strip())]
        expected_mq=16 if k<3 else 8
        assert len(mq)==expected_mq,(k,len(mq),expected_mq)
        for name in mq:
            assert name["size"]>=8.8,(k,"MQ labels too small",name)
            assert 40<=name["bbox"][0]<=50,(k,"label column drifting",name)
            y=name["bbox"][1]
            for prefix,expected_x in (("Scans",116),("Rs:",222),("R0:",347)):
                matches=[s for s in spans if s["text"].startswith(prefix) and
                         abs(s["bbox"][1]-y)<1.5]
                assert len(matches)==1,(k,name["text"],prefix,matches)
                assert abs(matches[0]["bbox"][0]-expected_x)<4,(
                    k,prefix,matches[0]["bbox"])
                assert matches[0]["size"]>=8.8,(k,prefix,matches[0]["size"])
            states=[s for s in spans if
                    (s["text"].startswith("SOURCE ONLY") or
                     s["text"].startswith("INSUFFICIENT SCANS")) and
                    abs(s["bbox"][1]-y)<1.5]
            assert len(states)==1,(k,name["text"],states)
            assert 495<=states[0]["bbox"][0]<=506,(k,"state column",states[0])
        total_mq+=len(mq)
        per_page.append({"page":k+1,"sensor_rows":len(mq),
            "minimum_MQ_label_size_pt":min(s["size"] for s in mq),
            "minimum_Rs_R0_column_size_pt":min(s["size"] for s in spans
                if s["text"].startswith("Rs:") or s["text"].startswith("R0:")),
            "research_only_marker":True,
            "source_column_positions_verified":True,
            "inside_page_bounds":True})
    for ix in range(7):
        assert f"MS-TEST-CYCLE-{ix}" in " ".join(all_text),(
            "fixture cycle omitted from rasterized PDF",ix)
    assert total_mq==56
    report={"schema":"hazrob-v6-n06c-PdfRenderer-text-legibility/1",
        "pdf_pages":doc.page_count,
        "original_fixture_sensor_rows":total_mq,
        "all_seven_fixture_cycles_present":True,
        "two_cycles_per_page":True,"field_ppm_certification":False,
        "research_g3":0,"pages":per_page}
    doc.close()
    return report

if __name__=="__main__":
    p=argparse.ArgumentParser()
    p.add_argument("pdf")
    p.add_argument("output_json")
    args=p.parse_args()
    report=validate(args.pdf)
    with open(args.output_json,"w",encoding="utf8") as f:
        json.dump(report,f,ensure_ascii=False,indent=2)
        f.write("\n")
    print("PASS Android actual PDF 4 pages, 56 MQ source rows, "
          "Rs/R0 fixed columns >=8.8 pt, no clipped text or omitted cycles")
